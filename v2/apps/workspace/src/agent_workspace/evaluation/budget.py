"""One persistent, fail-closed campaign budget shared by both comparison arms.

Authority is supplied by the operator, not generated by this module. Nothing
here discovers credentials or contacts a provider. Money is a conservative token
estimate, NOT an invoice. Uncertain dispatches are never refunded or replayed.
"""
from contextlib import contextmanager
from dataclasses import asdict, is_dataclass
from datetime import date, datetime
from enum import Enum
import hashlib
import json
import math
from pathlib import Path
import sqlite3
import time
import uuid

from agent_workspace.store import WorkspaceError


ENDPOINT = "https://api.openai.com/v1"
MODEL = "openai-responses:gpt-6.1-sol"
# Official pricing captured 2026-10-28. Reserve the MOST expensive short-context
# input rate (12h cache write), even though the adapter does not request caching.
# No built-in/provider-hosted tools, Fast/Ultrafast or regional tier is permitted.
PRICING = {
    "source": "https://developers.openai.com/api/docs/pricing",
    "captured_at": "2026-10-28",
    "input_standard_usd_per_million": 2,
    "input_reservation_usd_per_million": 5,
    "output_usd_per_million": 10,
    "max_short_input_tokens": 272000,
    "settlement": "conservative upper estimate, not invoiced cost",
}


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def _serialize(value):
    if is_dataclass(value):
        return asdict(value)
    if hasattr(value, "model_dump"):
        return value.model_dump(mode="json")
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    if isinstance(value, (set, frozenset)):
        return sorted(value, key=lambda item: json.dumps(item, default=_serialize, sort_keys=True))
    if isinstance(value, Enum):
        return value.value
    raise TypeError("unsupported_provider_request_value")


def input_bound(messages, settings, parameters):
    """Conservative UTF-8 byte/token bound + fixed provider envelope allowance.

    Only text and application function schemas are allowed. Binary/hosted-tool
    billing cannot be bounded by this estimator and is rejected. Provider token
    usage exceeding this reservation permanently stops the campaign.
    """
    raw = json.dumps([messages, settings, parameters], default=_serialize,
                     ensure_ascii=False, sort_keys=True).encode()
    if any(marker in raw for marker in (b'"image_url"', b'"image_data"', b'"audio"', b'"file_data"')):
        raise WorkspaceError("campaign_non_text_input")
    return len(raw) + 8192


class CampaignBudget:
    """Runtime plug-in: reserve(scope,...), settle(ticket,in,out), unknown(ticket).

    The active/unknown ticket is an indefinite fence, not a lease that expires on
    restart. Operator investigation may close/supersede a campaign but this
    implementation deliberately offers no reset/refund/resume switch.
    """

    def __init__(self, path, authority, manifest_digest, *, endpoint=ENDPOINT, model=MODEL):
        self.path = Path(path)
        self.authority = dict(authority)
        self.manifest_digest, self.endpoint, self.model = manifest_digest, endpoint, model
        if self.authority.get("ledger_path") is not None and Path(self.authority["ledger_path"]).resolve() != self.path.resolve():
            raise WorkspaceError("campaign_ledger_path_mismatch")
        self._validate_authority()
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.tx() as db:
            db.executescript("""
            CREATE TABLE IF NOT EXISTS campaign_meta(id INTEGER PRIMARY KEY CHECK(id=1),binding TEXT NOT NULL,stopped TEXT);
            CREATE TABLE IF NOT EXISTS campaign_runs(owner TEXT,run_id TEXT,case_id TEXT,arm TEXT,PRIMARY KEY(owner,run_id));
            CREATE TABLE IF NOT EXISTS campaign_dispatches(
              ticket TEXT PRIMARY KEY,owner TEXT,run_id TEXT,case_id TEXT,arm TEXT,
              status TEXT,input_bound INTEGER,output_bound INTEGER,reserved_microusd INTEGER,
              charged_microusd INTEGER,input_tokens INTEGER,output_tokens INTEGER,
              request_digest TEXT,started_at REAL,finished_at REAL);
            """)
            binding = digest([self.authority, self.manifest_digest, endpoint, model, PRICING])
            old = db.execute("SELECT binding FROM campaign_meta WHERE id=1").fetchone()
            if old and old[0] != binding:
                raise WorkspaceError("campaign_ledger_binding_changed")
            db.execute("INSERT OR IGNORE INTO campaign_meta(id,binding) VALUES(1,?)", (binding,))
        self.path.chmod(0o600)

    def _validate_authority(self):
        a = self.authority
        if a.get("approved") is not True or a.get("data_scope") != "synthetic-public-non-rtr":
            raise WorkspaceError("campaign_not_authorized")
        if (self.endpoint != ENDPOINT or self.model != MODEL or a.get("endpoint") != self.endpoint
                or a.get("model") != self.model or a.get("manifest_digest") != self.manifest_digest):
            raise WorkspaceError("campaign_authority_scope_mismatch")
        if not isinstance(self.manifest_digest, str) or len(self.manifest_digest) != 64:
            raise WorkspaceError("campaign_manifest_invalid")
        if not isinstance(a.get("case_ids"), list) or not a["case_ids"] or len(set(a["case_ids"])) != len(a["case_ids"]):
            raise WorkspaceError("campaign_cases_invalid")
        for key, maximum in (("limit_usd", 10), ("max_calls", 160), ("max_input_tokens", 100000), ("max_output_tokens", 2048)):
            n = a.get(key)
            if isinstance(n, bool) or not isinstance(n, (int, float)) or not math.isfinite(n) or not 0 < n <= maximum:
                raise WorkspaceError("campaign_limit_invalid")
        if a.get("concurrency") != 1 or a.get("repair_rounds", 0) not in (0, 1):
            raise WorkspaceError("campaign_limit_invalid")
        if not isinstance(a.get("approval_reference"), str) or not a["approval_reference"].strip():
            raise WorkspaceError("campaign_approval_reference_missing")
        expiry = a.get("expires_at")
        if not isinstance(expiry, (int, float)) or not math.isfinite(expiry) or expiry <= time.time():
            raise WorkspaceError("campaign_authority_expired")

    @contextmanager
    def tx(self):
        db = sqlite3.connect(self.path, timeout=10)
        db.row_factory = sqlite3.Row
        try:
            db.execute("PRAGMA synchronous=FULL")
            db.execute("BEGIN IMMEDIATE")
            yield db
            db.commit()
        except BaseException:
            db.rollback()
            raise
        finally:
            db.close()

    def bind_run(self, owner, run_id, case_id, arm):
        self._validate_authority()
        if case_id not in self.authority["case_ids"] or arm not in {"workspace", "direct-tool-agent", "smoke"}:
            raise WorkspaceError("campaign_run_out_of_scope")
        with self.tx() as db:
            prior = db.execute("SELECT case_id,arm FROM campaign_runs WHERE owner=? AND run_id=?", (owner, run_id)).fetchone()
            if prior and tuple(prior) != (case_id, arm):
                raise WorkspaceError("campaign_run_binding_changed")
            db.execute("INSERT OR IGNORE INTO campaign_runs VALUES(?,?,?,?)", (owner, run_id, case_id, arm))

    @staticmethod
    def _cost(inputs, outputs):
        # Units are microdollars; integer ceiling avoids float-budget creep.
        return math.ceil(inputs * PRICING["input_reservation_usd_per_million"]
                         + outputs * PRICING["output_usd_per_million"])

    async def reserve(self, scope, messages, model_settings, model_request_parameters):
        self._validate_authority()
        settings = model_settings or {}
        output = settings.get("max_tokens")
        if not isinstance(output, int) or isinstance(output, bool) or not 0 < output <= self.authority["max_output_tokens"]:
            raise WorkspaceError("campaign_output_not_bounded")
        # Positive allowlist: opaque extra-body/provider knobs could request
        # hosted tools, a more expensive tier or previous hidden server context.
        if (set(settings) - {"max_tokens", "openai_store", "openai_reasoning_effort"}
                or settings.get("openai_store", False) is not False
                or settings.get("openai_reasoning_effort", "low") != "low"):
            raise WorkspaceError("campaign_unpriced_setting")
        builtins = getattr(model_request_parameters, "builtin_tools", None) or getattr(model_request_parameters, "native_tools", None)
        if builtins or getattr(model_request_parameters, "allow_image_output", False):
            raise WorkspaceError("campaign_hosted_tools_forbidden")
        inputs = input_bound(messages, settings, model_request_parameters)
        if inputs > self.authority["max_input_tokens"]:
            raise WorkspaceError("campaign_input_limit")
        reserved = self._cost(inputs, output)
        owner, run_id = getattr(scope, "owner", None), getattr(scope, "run_id", None)
        with self.tx() as db:
            row = db.execute("SELECT * FROM campaign_runs WHERE owner=? AND run_id=?", (owner, run_id)).fetchone()
            if not row:
                raise WorkspaceError("campaign_run_not_bound")
            if db.execute("SELECT stopped FROM campaign_meta WHERE id=1").fetchone()[0]:
                raise WorkspaceError("campaign_stopped")
            if db.execute("SELECT 1 FROM campaign_dispatches WHERE status IN ('reserved','unknown')").fetchone():
                raise WorkspaceError("campaign_uncertain_or_concurrent_dispatch")
            count, charged = db.execute("SELECT COUNT(*),COALESCE(SUM(COALESCE(charged_microusd,reserved_microusd)),0) FROM campaign_dispatches").fetchone()
            if count >= self.authority["max_calls"] or charged + reserved > math.floor(self.authority["limit_usd"] * 1000000):
                raise WorkspaceError("campaign_budget_exhausted")
            ticket = str(uuid.uuid4())
            hashed = hashlib.sha256(json.dumps([messages, settings, model_request_parameters], default=_serialize, sort_keys=True).encode()).hexdigest()
            db.execute("INSERT INTO campaign_dispatches VALUES(?,?,?,?,?,'reserved',?,?,?,NULL,NULL,NULL,?,?,NULL)",
                       (ticket, owner, run_id, row["case_id"], row["arm"], inputs, output, reserved, hashed, time.time()))
        return ticket

    async def settle(self, ticket, input_tokens, output_tokens):
        invalid = (isinstance(input_tokens, bool) or isinstance(output_tokens, bool)
                   or not isinstance(input_tokens, int) or not isinstance(output_tokens, int)
                   or min(input_tokens, output_tokens) < 0)
        with self.tx() as db:
            row = db.execute("SELECT * FROM campaign_dispatches WHERE ticket=?", (ticket,)).fetchone()
            if not row or row["status"] != "reserved":
                raise WorkspaceError("campaign_ticket_not_pending")
            invalid = invalid or input_tokens > row["input_bound"] or output_tokens > row["output_bound"]
            if invalid:
                db.execute("UPDATE campaign_dispatches SET status='unknown',finished_at=? WHERE ticket=?", (time.time(), ticket))
                db.execute("UPDATE campaign_meta SET stopped='usage_exceeded_reservation' WHERE id=1")
            else:
                db.execute("UPDATE campaign_dispatches SET status='settled',charged_microusd=?,input_tokens=?,output_tokens=?,finished_at=? WHERE ticket=?",
                           (self._cost(input_tokens, output_tokens), input_tokens, output_tokens, time.time(), ticket))
        if invalid:
            raise WorkspaceError("campaign_usage_unbounded")

    async def unknown(self, ticket):
        with self.tx() as db:
            db.execute("UPDATE campaign_dispatches SET status='unknown',finished_at=? WHERE ticket=? AND status='reserved'", (time.time(), ticket))
            if db.execute("SELECT 1 FROM campaign_dispatches WHERE ticket=? AND status='unknown'", (ticket,)).fetchone():
                db.execute("UPDATE campaign_meta SET stopped='uncertain_dispatch' WHERE id=1")

    def snapshot(self):
        with self.tx() as db:
            rows = [dict(row) for row in db.execute("SELECT ticket,case_id,arm,status,input_bound,output_bound,reserved_microusd,charged_microusd,input_tokens,output_tokens,started_at,finished_at FROM campaign_dispatches ORDER BY started_at")]
            stopped = db.execute("SELECT stopped FROM campaign_meta WHERE id=1").fetchone()[0]
        return dict(manifest_digest=self.manifest_digest, pricing=PRICING, calls=len(rows),
                    conservative_charged_or_reserved_usd=sum(r["charged_microusd"] if r["charged_microusd"] is not None else r["reserved_microusd"] for r in rows) / 1000000,
                    invoice_usd=None, stopped=stopped, dispatches=rows)
